TURN_LENGTH_DAYS = 8
TOTAL_TURNS = 5

RU_MONTHS = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля", 5: "мая", 6: "июня",
    7: "июля", 8: "августа", 9: "сентября", 10: "октября", 11: "ноября", 12: "декабря",
}


def ru_date(d: date) -> str:
    return f"{d.day} {RU_MONTHS[d.month]} {d.year}"


def turn_start(turn: int) -> date:
    return START_DATE + timedelta(days=(turn - 1) * TURN_LENGTH_DAYS)


def turn_end(turn: int) -> date:
    return turn_start(turn) + timedelta(days=TURN_LENGTH_DAYS - 1)


GAME_DEADLINE = turn_end(TOTAL_TURNS)
GAME_DEADLINE_ISO = GAME_DEADLINE.isoformat()
GAME_DEADLINE_RU = ru_date(GAME_DEADLINE)

